#!/usr/bin/env bash
# Builds the aquarevwater.us Engineering landing page from the master in this folder.
# Re-run after any change to AquaRev_Engineering_Page.html, then push.
#
#   Page: /engineering  →  engineering.css / engineering.js / webflow-embed-engineering.html / preview.html
#
# The JS injects the page markup into an empty <div id="aren"> and every style is scoped under
# #aren, so Webflow's global styles never reach the page and vice versa (same pattern as the
# Specifications, Data and Certification pages).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MASTER="$HERE/AquaRev_Engineering_Page.html"
PAGES="https://jeffatley-web.github.io/aquarev_engineering"
STAMP="$(date +%Y%m%d%H%M)"
FONTS='https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@75..100,400..800&family=Source+Sans+3:ital,wght@0,400;0,600;0,700;1,400&family=IBM+Plex+Mono:wght@400;500&display=swap'

cd "$HERE"

# scope_css ROOT — reads CSS on stdin, writes CSS scoped under #ROOT on stdout
scope_css() {
  local root="$1"
  sed -E \
    -e 's#/\*[^*]*\*/##g' \
    -e "s/^:root\{/#${root}{/" \
    -e "s/:root:not\(\[data-theme=\"light\"\]\)\{/#${root}{/" \
    -e "s/^:root\[data-theme=\"dark\"\]\{/#${root}[data-theme=\"dark\"]{/" \
    -e "s/^body\{/#${root}{/" \
  | perl -e '
    my $css = do { local $/; <STDIN> }; my $root = shift @ARGV; my $out = "";
    while ($css =~ /\G([^{}]*)([{}])/gc) {
      my ($txt, $br) = ($1, $2);
      if ($br eq "{") {
        if ($txt =~ /^\s*@/) { $out .= $txt . "{"; }
        else {
          my ($lead) = $txt =~ /^(\s*)/;
          my @parts = map { my $s = $_; $s =~ s/^\s+|\s+$//g; ($s =~ /^#$root/ ? $s : "#$root $s") } split /,(?![^(]*\))/, $txt;
          $out .= $lead . join(", ", @parts) . "{";
        }
      } else { $out .= $txt . "}"; }
    }
    $out .= substr($css, pos($css) // 0); print $out;
  ' "$root"
}

# rewrite_links — local image paths become GitHub Pages URLs
rewrite_links() {
  sed -E -e "s|src=\"img/|src=\"$PAGES/img/|g"
}

{
  echo "/* AquaRev Engineering landing page. Generated by build.sh from the master; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$MASTER" | scope_css aren
} > engineering.css

{
  echo "/* AquaRev Engineering landing page. Generated by build.sh from the master; do not edit by hand. */"
  echo "(function(){"
  echo "var root=document.getElementById('aren'); if(!root) return;"
  echo "root.innerHTML=\`"
  awk '/^<div class="page">$/{f=1} f&&/^<script>$/{exit} f{print}' "$MASTER" | rewrite_links | sed -E 's/`/\\`/g; s/\$\{/\\${/g'
  echo "\`;"
  # measure the site's sticky nav so this page's section bar sits below it
  cat <<'EOF'
(function(){
  function navOffset(){
    var nav=document.querySelector('.w-nav, nav.w-nav'); var h=0;
    if(nav){ var cs=getComputedStyle(nav); if(cs.position==='sticky'||cs.position==='fixed'){ h=Math.round(nav.getBoundingClientRect().height); } }
    root.style.setProperty('--aren-sticky-top', h+'px');
  }
  navOffset(); window.addEventListener('resize', navOffset); window.addEventListener('load', navOffset);
})();
EOF
  awk '/^<script>$/{f=1;next} /^<\/script>$/{f=0} f' "$MASTER"
  echo "})();"
} > engineering.js

cat > webflow-embed-engineering.html <<EOF
<!-- AquaRev Engineering landing page. Paste this whole block into a Webflow Embed element on /engineering.
     CSS and JS are hosted on GitHub Pages; bump the ?v= values after pushing changes. -->
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="$PAGES/engineering.css?v=$STAMP">
<div id="aren" data-theme="dark"></div>
<script defer src="$PAGES/engineering.js?v=$STAMP"></script>
EOF

cat > preview.html <<EOF
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Preview: AquaRev Engineering (local, mirrors the Webflow embed)</title>
<style>body{margin:0;background:#0E171E;font-family:sans-serif}</style>
</head>
<body>
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="engineering.css">
<div id="aren" data-theme="dark"></div>
<script defer src="engineering.js"></script>
</body>
</html>
EOF

wc -c engineering.css engineering.js webflow-embed-engineering.html img/*
